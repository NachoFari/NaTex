function applyLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('natex_language', lang);
    const dict = i18n[lang] || i18n.es;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (dict[key].includes('<') && dict[key].includes('>')) {
                el.innerHTML = dict[key];
            } else {
                el.innerText = dict[key];
            }
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key]) {
            el.title = dict[key];
        }
    });
    const btnEs = document.getElementById('btnLangEs');
    const btnEn = document.getElementById('btnLangEn');
    if (btnEs && btnEn) {
        btnEs.classList.toggle('active', lang === 'es');
        btnEn.classList.toggle('active', lang === 'en');
    }
    if (typeof renderThemeSelectorGrid === 'function') {
        renderThemeSelectorGrid(typeof currentTheme !== 'undefined' ? currentTheme : 'fox');
    }
    if (typeof updateThemeMascotIcons === 'function') {
        updateThemeMascotIcons(typeof currentTheme !== 'undefined' ? currentTheme : 'fox');
    }
    if (typeof updateEditorMetrics === 'function') {
        updateEditorMetrics();
    }
    if (typeof window.syncThemeEffectsFrequencyUI === 'function') {
        window.syncThemeEffectsFrequencyUI();
    }
}

window.i18n = i18n;
window.applyLanguage = applyLanguage;
